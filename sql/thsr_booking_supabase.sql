-- ============================================================================
-- 高鐵訂票系統：3NF 修正版資料庫結構
-- 適用：Supabase / PostgreSQL 15 以上
--
-- 使用方式：
-- 1. 直接在 Supabase SQL Editor 執行本檔，不需要 CREATE DATABASE 或 USE。
-- 2. 建議在尚未建立同名資料表的專案中執行一次。
-- 3. 全部 DDL 包在同一個交易中；任一步驟失敗時，不會留下半套結構。
--
-- 設計重點：
-- 1. booking_items 不重複保存 schedule_id；班次可由起訖停靠點決定。
-- 2. schedule_segments 明確表示兩個相鄰停靠點之間的行車區間。
-- 3. seat_segment_reservations 以「區間 + 座位」為主鍵，防止重複售票。
-- 4. 票種與成交票價只保存在 booking_items；tickets 不再重複保存。
-- 5. 訂單總額由 v_booking_totals 即時計算，避免 total_amount 更新異常。
-- 6. fares 保存起迄站、座位類型與票種的現行售價。
-- 7. seats 明確保存座位位置，不由應用程式依座號推測靠窗或走道。
-- ============================================================================

