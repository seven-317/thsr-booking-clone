-- 驗證行車區間的起訖停靠點屬於同一班次，而且兩站必須相鄰。
CREATE OR REPLACE FUNCTION fn_validate_schedule_segment_insert()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    v_from_schedule bigint;
    v_to_schedule   bigint;
    v_from_order    smallint;
    v_to_order      smallint;
BEGIN
    SELECT schedule_id, stop_order
      INTO v_from_schedule, v_from_order
      FROM train_stops
     WHERE stop_id = NEW.from_stop_id;

    SELECT schedule_id, stop_order
      INTO v_to_schedule, v_to_order
      FROM train_stops
     WHERE stop_id = NEW.to_stop_id;

    IF v_from_schedule IS DISTINCT FROM v_to_schedule THEN
        RAISE EXCEPTION '區間的起點與終點必須屬於同一班次';
    END IF;

    IF v_to_order IS DISTINCT FROM v_from_order + 1 THEN
        RAISE EXCEPTION '區間的終點必須是起點的下一個停靠站';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER bi_schedule_segments_validate
BEFORE INSERT ON schedule_segments
FOR EACH ROW
EXECUTE FUNCTION fn_validate_schedule_segment_insert();

-- 區間建立後不可改接其他停靠點，以免既有預訂指向錯誤區間。
CREATE OR REPLACE FUNCTION fn_prevent_schedule_segment_endpoint_update()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
    IF NEW.from_stop_id IS DISTINCT FROM OLD.from_stop_id
       OR NEW.to_stop_id IS DISTINCT FROM OLD.to_stop_id THEN
        RAISE EXCEPTION '不可修改既有區間端點；請刪除後重新建立';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER bu_schedule_segments_validate
BEFORE UPDATE ON schedule_segments
FOR EACH ROW
EXECUTE FUNCTION fn_prevent_schedule_segment_endpoint_update();

-- 驗證訂票項目的班次、起訖順序、座位列車、會員與完整區間。
CREATE OR REPLACE FUNCTION fn_validate_booking_item_insert()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    v_origin_schedule     bigint;
    v_destination_sched  bigint;
    v_origin_order        smallint;
    v_destination_order   smallint;
    v_schedule_train      bigint;
    v_seat_train          bigint;
    v_booking_member      bigint;
    v_passenger_member    bigint;
    v_segment_count       bigint;
BEGIN
    SELECT schedule_id, stop_order
      INTO v_origin_schedule, v_origin_order
      FROM train_stops
     WHERE stop_id = NEW.origin_stop_id;

    SELECT schedule_id, stop_order
      INTO v_destination_sched, v_destination_order
      FROM train_stops
     WHERE stop_id = NEW.destination_stop_id;

    IF v_origin_schedule IS DISTINCT FROM v_destination_sched THEN
        RAISE EXCEPTION '起站與迄站必須屬於同一班次';
    END IF;

    IF v_origin_order >= v_destination_order THEN
        RAISE EXCEPTION '起站順序必須早於迄站';
    END IF;

    SELECT train_id
      INTO v_schedule_train
      FROM train_schedules
     WHERE schedule_id = v_origin_schedule;

    SELECT train_id
      INTO v_seat_train
      FROM seats
     WHERE seat_id = NEW.seat_id;

    IF v_schedule_train IS DISTINCT FROM v_seat_train THEN
        RAISE EXCEPTION '所選座位不屬於此班次的列車';
    END IF;

    SELECT member_id
      INTO v_booking_member
      FROM bookings
     WHERE booking_id = NEW.booking_id;

    SELECT member_id
      INTO v_passenger_member
      FROM passengers
     WHERE passenger_id = NEW.passenger_id;

    IF v_booking_member IS DISTINCT FROM v_passenger_member THEN
        RAISE EXCEPTION '乘客資料不屬於下單會員';
    END IF;

    -- 旅程跨越 n 個停靠序差，就必須存在 n 個相鄰區間。
    SELECT COUNT(*)
      INTO v_segment_count
      FROM schedule_segments AS sg
      JOIN train_stops AS fs ON fs.stop_id = sg.from_stop_id
     WHERE fs.schedule_id = v_origin_schedule
       AND fs.stop_order >= v_origin_order
       AND fs.stop_order < v_destination_order;

    IF v_segment_count <> v_destination_order - v_origin_order THEN
        RAISE EXCEPTION '此班次的相鄰行車區間尚未完整建立';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER bi_booking_items_validate
BEFORE INSERT ON booking_items
FOR EACH ROW
EXECUTE FUNCTION fn_validate_booking_item_insert();

-- 已鎖位後不可直接更換訂單、乘客、座位或行程。
CREATE OR REPLACE FUNCTION fn_prevent_booking_item_trip_update()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
    IF NEW.booking_id IS DISTINCT FROM OLD.booking_id
       OR NEW.passenger_id IS DISTINCT FROM OLD.passenger_id
       OR NEW.seat_id IS DISTINCT FROM OLD.seat_id
       OR NEW.origin_stop_id IS DISTINCT FROM OLD.origin_stop_id
       OR NEW.destination_stop_id IS DISTINCT FROM OLD.destination_stop_id THEN
        RAISE EXCEPTION '不可直接修改已鎖位項目的訂單、乘客、座位或行程';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER bu_booking_items_immutable_trip
BEFORE UPDATE ON booking_items
FOR EACH ROW
EXECUTE FUNCTION fn_prevent_booking_item_trip_update();

-- 新增訂票項目後，自動鎖住旅程涵蓋的每個相鄰區間。
-- 若任一區間已被同一座位占用，複合主鍵會讓整筆交易原子性失敗。
CREATE OR REPLACE FUNCTION fn_reserve_booking_item_segments()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
    INSERT INTO seat_segment_reservations (
        segment_id,
        seat_id,
        booking_item_id
    )
    SELECT
        sg.segment_id,
        NEW.seat_id,
        NEW.booking_item_id
      FROM schedule_segments AS sg
      JOIN train_stops AS fs ON fs.stop_id = sg.from_stop_id
      JOIN train_stops AS os ON os.stop_id = NEW.origin_stop_id
      JOIN train_stops AS ds ON ds.stop_id = NEW.destination_stop_id
     WHERE fs.schedule_id = os.schedule_id
       AND fs.stop_order >= os.stop_order
       AND fs.stop_order < ds.stop_order;

    RETURN NEW;
END;
$$;

CREATE TRIGGER ai_booking_items_reserve_segments
AFTER INSERT ON booking_items
FOR EACH ROW
EXECUTE FUNCTION fn_reserve_booking_item_segments();

-- ----------------------------------------------------------------------------
-- 衍生查詢：訂單總額不重複存入 bookings，而由明細即時計算。
-- ----------------------------------------------------------------------------

CREATE OR REPLACE VIEW v_booking_totals AS
SELECT
    b.booking_id,
    b.booking_number,
    COALESCE(SUM(bi.fare_amount), 0.00::numeric) AS total_amount
FROM bookings AS b
LEFT JOIN booking_items AS bi
       ON bi.booking_id = b.booking_id
GROUP BY b.booking_id, b.booking_number;

COMMENT ON VIEW v_booking_totals IS '依訂票項目即時計算的訂單總額';

COMMIT;
